# 진행 순서 (위 표의 적힌 순서)
MAP_ORDER = list(MAP_INFO)


def map_name(group_number):
    g, n = group_number
    info = MAP_INFO.get((g, n))
    return info[0] if info else f"{g}:{n}"


def map_size(group_number):
    """(가로, 세로) 칸 수. 표에 없으면 None"""
    info = MAP_INFO.get(tuple(group_number))
    return (info[1], info[2]) if info else None
