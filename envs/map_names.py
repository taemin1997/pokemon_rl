# (그룹, 번호): (이름, 가로 칸, 세로 칸)
# 크기: map_constants.asm의 블록 수 x 2. 블록 1개 = 32픽셀 = 걸음 2칸이라서
# 메모리의 x, y 좌표도 이 "걸음 칸" 단위임
